# -*- coding: utf-8 -*-
"""개인정보 꼴 가리기 — SR-24. 질문에서 여섯 꼴을 찾아 자리 표시로 바꾼다.

가린 질문만 뒤로 흐른다. 가렸으면 재사용 답변의 저장과 조회, 질문 낱말 지문을 쓰지 않는다.
순서가 뜻이 있다. 주민등록번호와 카드번호를 먼저 떼야 전화번호나 계좌번호로 잘못 읽히지 않는다.
"""
import re

_D = r"(?<![0-9])"      # 앞에 숫자가 이어지지 않음
_E = r"(?![0-9])"       # 뒤에 숫자가 이어지지 않음

PATTERNS = [
    ("[이메일]", re.compile(r"[A-Za-z0-9._%+\-]+@[A-Za-z0-9\-]+(?:\.[A-Za-z0-9\-]+)+")),
    ("[주민등록번호]", re.compile(_D + r"\d{2}(?:0[1-9]|1[0-2])(?:0[1-9]|[12]\d|3[01])[\s\-]?[1-8]\d{6}" + _E)),
    ("[카드번호]", re.compile(_D + r"\d{4}[\s\-]?\d{4}[\s\-]?\d{4}[\s\-]?\d{3,4}" + _E)),
    ("[전화번호]", re.compile(_D + r"(?:\+?82[\s\-]?1[016789]|01[016789])[\s\-.]?\d{3,4}[\s\-.]?\d{4}" + _E)),
    ("[전화번호]", re.compile(_D + r"(?:\+?82[\s\-]?|0)(?:2|3[1-3]|4[1-4]|5[1-5]|6[1-4]|70)[\s\-.]\d{3,4}[\s\-.]\d{4}" + _E)),
    ("[IP]", re.compile(_D + r"(?:(?:25[0-5]|2[0-4]\d|1?\d?\d)\.){3}(?:25[0-5]|2[0-4]\d|1?\d?\d)" + _E)),
    ("[IP]", re.compile(r"(?<![0-9A-Fa-f:])(?:[0-9A-Fa-f]{1,4}:){4,7}[0-9A-Fa-f]{1,4}(?![0-9A-Fa-f:])")),
    # 붙임표로 나눈 숫자 묶음. 날짜(2026-09-08)는 계좌번호가 아니므로 뺀다.
    # 사업자등록번호(3-2-5)도 이 꼴에 걸린다. 조직을 짚는 값이라 같이 가린다
    ("[계좌번호]", re.compile(_D + r"(?!(?:19|20)\d{2}-\d{1,2}-\d{1,2}" + _E + r")\d{2,6}-\d{2,6}-\d{2,8}(?:-\d{1,3})?" + _E)),
    # 붙임표 없는 긴 숫자는 앞에 「계좌」 가 있을 때만. 숫자만 보면 식별 번호와 시각이 다 걸린다
    ("[계좌번호]", re.compile(r"(?<=계좌)(?:\s*번호)?\s*[:：]?\s*\d{10,14}" + _E)),
]


def mask(text):
    """(가린 글, 가린 꼴 목록). 가린 것이 없으면 목록이 빈다."""
    if not text:
        return text, []
    found = []
    out = text
    for label, p in PATTERNS:
        out, n = p.subn(label, out)
        if n and label not in found:
            found.append(label)
    return out, found


def has_pii(text):
    """스냅샷 반출 관문이 쓴다 (F-22 처리 2)."""
    if not text:
        return None
    for label, p in PATTERNS:
        m = p.search(text)
        if m:
            return label
    return None
