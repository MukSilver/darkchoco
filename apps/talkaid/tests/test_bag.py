#!/usr/bin/env python3
"""말주머니 시험. **창을 안 만든다.** 어느 판에서나 돈다.

    python tests/test_bag.py

여기서 보는 것은 하나다 — **같은 사람이 같은 말을 두 번 듣지 않는가.**
그게 안 되면 상대가 스크립트로 눈치채고 그 컨택은 되살릴 수 없다.

씨앗을 고정한 난수를 넣어 돌리므로 결과가 매번 같다.
"""
from __future__ import annotations

import json
import random
import sys
import tempfile
from pathlib import Path

# 한국어 윈도우 콘솔은 cp949 다. 실패 메시지에 em dash 나 화살표가 있으면
# UnicodeEncodeError 로 죽어서 **무엇이 실패했는지 못 보여 준다.**
# 깨지는 글자만 ? 로 바꾸고 계속 찍는다.
try:
    sys.stdout.reconfigure(errors="replace")
except (AttributeError, ValueError):   # 파이썬이 낮거나 리다이렉트된 경우
    pass


sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import bag as B  # noqa: E402

fails = []


def check(name, got, want):
    if got != want:
        fails.append("%s\n     받음 %r\n     기대 %r" % (name, got, want))


def 씨앗(n=7):
    return B.주머니들(난수=random.Random(n))


후보4 = ["a", "b", "c", "d"]
자리 = ("2", "사는 쪽", "값 묻기", "얼마에 파나요")

# ── 한 바퀴 안에는 안 겹친다 ─────────────────────
# 이것이 random.choice 를 안 쓰는 이유다. 넷이면 네 번에 한 번 직전과 겹친다
ㅁ = 씨앗()
한바퀴 = [ㅁ.뽑기(*자리, 후보4) for _ in range(4)]
check("한 바퀴에 넷이 다 나온다", sorted(한바퀴), sorted(후보4))
check("한 바퀴 안에 겹치는 것이 없다", len(set(한바퀴)), 4)

# ── 이음매에서도 안 겹친다 ───────────────────────
# 주머니가 비어 다시 섞을 때 새 첫 장이 직전 마지막과 같으면 두 번 연달아 나간다
for 씨 in range(40):
    ㅁ = B.주머니들(난수=random.Random(씨))
    줄 = [ㅁ.뽑기(*자리, 후보4) for _ in range(20)]
    붙은것 = [i for i in range(1, len(줄)) if 줄[i] == 줄[i - 1]]
    if 붙은것:
        fails.append("씨앗 %d 에서 연달아 같은 것이 나왔다: %d 번째 %r"
                     % (씨, 붙은것[0], 줄[붙은것[0]]))
        break

# ── 지금() 과 뽑기() 가 어긋나지 않는다 ──────────
# 화면에 보이는 것과 클립보드에 들어가는 것이 다르면 안 읽은 문장이 나간다
ㅁ = 씨앗()
for _ in range(9):
    보인것 = ㅁ.지금(*자리, 후보4)
    나간것 = ㅁ.뽑기(*자리, 후보4)
    if 보인것 != 나간것:
        fails.append("보인 것과 나간 것이 다르다: %r vs %r" % (보인것, 나간것))
        break

# ── 상대가 다르면 자루도 다르다 ──────────────────
# 문제는 「우리가 같은 말을 자주 쓰는 것」이 아니라
# 「한 사람이 우리에게서 같은 말을 두 번 듣는 것」이다
ㅁ = 씨앗()
둘 = [ㅁ.뽑기("2", "사는 쪽", "값 묻기", "얼마에 파나요", 후보4) for _ in range(4)]
셋 = [ㅁ.뽑기("3", "사는 쪽", "값 묻기", "얼마에 파나요", 후보4) for _ in range(4)]
check("2번 상대는 한 바퀴를 다 돌았다", sorted(둘), sorted(후보4))
check("3번 상대도 따로 한 바퀴를 돈다", sorted(셋), sorted(후보4))
check("자루가 둘로 갈렸다", len(ㅁ.자루), 2)

# 페르소나가 다르면 그것도 갈린다
ㅁ.뽑기("2", "파는 쪽", "값 묻기", "얼마에 파나요", 후보4)
check("페르소나로도 갈린다", len(ㅁ.자루), 3)

# ── 후보가 하나면 그대로 ─────────────────────────
ㅁ = 씨앗()
check("하나뿐이면 늘 그것", [ㅁ.뽑기(*자리, ["only"]) for _ in range(3)],
      ["only"] * 3)
check("빈 후보는 빈 글", ㅁ.뽑기(*자리, []), "")
check("빈 후보는 지금도 빈 글", ㅁ.지금(*자리, []), "")

# ── 넘기기는 안 닳는다 ───────────────────────────
# [↻] 는 미루는 것이지 쓰는 것이 아니다. 한 바퀴가 줄면 안 된다
ㅁ = 씨앗()
처음 = ㅁ.지금(*자리, 후보4)
ㅁ.넘기기(*자리, 후보4)
다음 = ㅁ.지금(*자리, 후보4)
check("넘기면 다른 것이 걸린다", 처음 != 다음, True)
남은수 = len(ㅁ.자루[B.열쇠(*자리)]["남은"])
check("넘겨도 한 바퀴가 안 줄었다", 남은수, 4)
# 넷을 다 넘기면 처음으로 돌아온다
for _ in range(3):
    ㅁ.넘기기(*자리, 후보4)
check("넷을 다 넘기면 처음으로", ㅁ.지금(*자리, 후보4), 처음)

# ── 후보가 바뀌면 그 주머니를 버린다 ─────────────
# 번호만 저장하므로 목록이 바뀌면 번호가 엉뚱한 것을 가리킨다
ㅁ = 씨앗()
ㅁ.뽑기(*자리, 후보4)
check("네 개짜리로 기록됐다", ㅁ.자루[B.열쇠(*자리)]["n"], 4)
ㅁ.뽑기(*자리, ["a", "b"])
check("둘로 바뀌면 다시 잡는다", ㅁ.자루[B.열쇠(*자리)]["n"], 2)
check("남은 번호가 범위 안이다",
      all(0 <= i < 2 for i in ㅁ.자루[B.열쇠(*자리)]["남은"]), True)

# ── 저장하고 읽으면 이어진다 ─────────────────────
with tempfile.TemporaryDirectory() as td:
    p = Path(td) / "talkaid_bag.json"
    ㅁ = 씨앗()
    앞의것 = [ㅁ.뽑기(*자리, 후보4) for _ in range(2)]
    ㅁ.별칭 = ["muse", "2", "3", "4", "5"]
    check("썼다", ㅁ.쓰기(p), True)

    ㄴ = B.주머니들.읽기(p, 난수=random.Random(7))
    check("별칭이 살아 있다", ㄴ.별칭[0], "muse")
    뒤의것 = [ㄴ.뽑기(*자리, 후보4) for _ in range(2)]
    check("창을 다시 띄워도 한 바퀴가 이어진다",
          sorted(앞의것 + 뒤의것), sorted(후보4))

    # **파일에 영어 문장이 남으면 안 된다.** 남으면 그게 곧 발화 기록이다
    글 = p.read_text(encoding="utf-8")
    for 새면안됨 in 후보4:
        if '"%s"' % 새면안됨 in 글:
            fails.append("자루 파일에 영어 문장이 남았다: %r" % 새면안됨)
    check("한국어 열쇠는 남는다 (상용구는 레포에 있는 것이라 괜찮다)",
          "얼마에 파나요" in 글, True)

# ── 깨진 파일에도 안 죽는다 ──────────────────────
with tempfile.TemporaryDirectory() as td:
    p = Path(td) / "깨진.json"
    p.write_text("{이건 JSON 이 아니다", encoding="utf-8")
    ㄴ = B.주머니들.읽기(p)
    check("깨졌으면 빈 것으로", ㄴ.자루, {})
    check("별칭은 기본값", ㄴ.별칭, B.기본별칭)
    check("그래도 돈다", ㄴ.뽑기(*자리, ["x"]), "x")

    p2 = Path(td) / "없다.json"
    check("파일이 없어도 빈 것으로", B.주머니들.읽기(p2).자루, {})

    # BOM 이 붙어도 읽는다. 사람이 메모장으로 고칠 수 있는 자리다
    p3 = Path(td) / "bom.json"
    p3.write_text('﻿{"별칭": ["a"], "자루": {}}', encoding="utf-8")
    check("BOM 이 붙어도 읽는다", B.주머니들.읽기(p3).별칭, ["a"])

# ── 후보뽑기 ─────────────────────────────────────
# 영어 는 스칼라로 남기고 영어들 을 덧붙인다. 같은 글을 두 군데 안 적는다
check("영어들이 없으면 하나",
      B.후보뽑기({"영어": "hey"}), ["hey"])
check("영어들을 덧붙인다",
      B.후보뽑기({"영어": "hey", "영어들": ["hi", "yo"]}), ["hey", "hi", "yo"])
check("겹치면 한 번만",
      B.후보뽑기({"영어": "hey", "영어들": ["hey", "hi"]}), ["hey", "hi"])
check("빈 것은 버린다",
      B.후보뽑기({"영어": "hey", "영어들": ["", "  ", "hi"]}), ["hey", "hi"])
check("고정이면 첫 것만",
      B.후보뽑기({"영어": "hey", "영어들": ["hi"], "섞기": "고정"}), ["hey"])
check("영어가 없으면 빈 목록", B.후보뽑기({"영어들": ["hi"]}), ["hi"])
check("둘 다 없으면 빈 목록", B.후보뽑기({}), [])
check("영어들이 목록이 아니면 무시",
      B.후보뽑기({"영어": "hey", "영어들": "hi"}), ["hey"])

# ── 열쇠 ─────────────────────────────────────────
check("네 조각을 이어 붙인다",
      B.열쇠("2", "사는 쪽", "값 묻기", "얼마에"), "2|사는 쪽|값 묻기|얼마에")
# 별칭에 | 를 넣어도 열쇠가 안 섞인다
check("구분자를 막는다",
      B.열쇠("a|b", "p", "g", "k"), "a/b|p|g|k")

# ── 결과 ─────────────────────────────────────────
if fails:
    print("실패 %d" % len(fails))
    for f in fails:
        print("  - %s" % f)
    sys.exit(1)
print("통과. 시험 11 묶음")
