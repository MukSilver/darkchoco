"""명부 한 줄.

다크웹 DB 세 개(포럼·텔레그램·랜섬웨어)가 24칸을 공유합니다. 대상이
포럼이든 채널이든 랜섬 그룹이든, 알아내야 하는 것이 같습니다.

    어디가 있나 · 지금 살아있나 · 얼마나 큰가

그래서 조사 방법만 갈래마다 다르고, 내놓는 것은 이 한 가지입니다.

지키는 것 셋입니다.

  1. **노션 칸을 늘리지 않습니다.** 다크웹 DB 스키마가 LLM 다크웹 RAG 의
     근간이라 바꾸면 그쪽이 흔들립니다. 기존 칸만 씁니다.
  2. **사람이 쓴 것을 안 지웁니다.** `규모` 칸에 사람이 적은 조사 결과가
     섞여 있습니다. 그 자체가 결과라 지우면 안 됩니다.
  3. **못 본 것을 없음으로 적지 않습니다.** 못 봤으면 왜인지 남깁니다.
     빈칸으로 두면 나중에 실제로 빈 것으로 읽힙니다.

숫자는 우리 쪽 SQLite 에 시계열로 쌓고, 노션에는 사람이 읽을 한 줄만
넣습니다. 그래야 언제부터 죽었는지, 구독자가 줄고 있는지를 볼 수 있습니다.
"""

from __future__ import annotations

import re
from dataclasses import asdict, dataclass, field
from datetime import datetime, timezone

__all__ = ["Place", "기계칸", "덮어쓰는칸", "합치는칸", "빈칸만칸",
           "지금", "규모합치기", "기계가_쓴_줄"]


def 지금() -> str:
    return datetime.now(timezone.utc).astimezone().isoformat(timespec="seconds")


# 기계가 채워도 되는 노션 칸입니다. 전부 기존 칸이고, 다루는 법이 셋으로
# 갈립니다. 이 갈래를 안 지키면 사람이 조사한 것을 지웁니다.
#
#   덮어쓰는칸   기계 소관입니다. 볼 때마다 새 값으로 바꿉니다
#   합치는칸     사람 글과 섞여 있습니다. 기계 줄만 갈아 끼웁니다
#   빈칸만칸     사람이 이미 썼으면 안 건드립니다. 비어 있을 때만 채웁니다
#
# 목록 밖은 아예 안 씁니다. 조사 단계·유통 자리·비고·순위·웹에 올림·
# 담당자·DB 반영·일부러 반출하지 않음은 사람이 판단하는 칸입니다.
덮어쓰는칸 = {"상태", "확인일", "주소", "어니언 주소", "최근 활동"}
합치는칸 = {"규모", "피해 대상", "한국 관련 유출"}
빈칸만칸 = {"사용 언어", "들어가는 법", "이전 주소", "이전 이름·별칭",
          "어떤 곳인지", "가입 필요", "형식", "종류", "출처", "연락수단",
          "조사 단계", "연결된 곳"}
기계칸 = 덮어쓰는칸 | 합치는칸 | 빈칸만칸

# 기계가 쓴 줄을 알아보는 꼴입니다. 사람 글과 갈라내려는 것입니다.
#   구독자 8,145 (2026-08-28 기준)
#   회원 349,000 · 게시물 821,000 (2026-08-28 기준)
_기계줄 = re.compile(
    r"^\s*(?:구독자|회원|게시물|피해 기업)[\s\d,·]*"
    r"(?:구독자|회원|게시물|피해 기업)?[\s\d,·]*"
    r"(?:\s*안팎)?\s*\(\d{4}-\d{2}-\d{2} 기준\)\s*$")


# 숫자만 있는 줄. 이수빈 님이 8/26 에 넣은 "646" 같은 것입니다.
# 새 줄이 같은 것을 더 자세히 말하므로 갈아 끼웁니다.
_숫자만 = re.compile(r"^\s*[\d,\.\s]{1,15}\s*$")

# 기계가 쓴 줄은 전부 "(YYYY-MM-DD 기준)" 으로 끝납니다. 규모 말고
# 피해 대상·한국 관련 유출도 같은 꼴을 씁니다.
#
# 사람이 쓴 "구독자 1,440명 (2026.08.04 13:32 GMT+9 기준)" 은 점을 쓰고
# 시각까지 적어 여기 안 걸립니다. 그대로 남습니다.
_기준줄 = re.compile(r"\(\d{4}-\d{2}-\d{2} 기준\)\s*$")


def 기계가_쓴_줄(줄: str) -> bool:
    """새 줄로 갈아 끼워도 되는 줄인가.

    사람이 문장으로 적은 것은 아닙니다. 그것은 조사 결과라 남깁니다.
        구독자 1,440명 (2026.08.04 13:32 GMT+9 기준)   남깁니다
        멤버 수·게시물 수 못 셈 …                        남깁니다
        646                                          갈아 끼웁니다
        구독자 8,145 (2026-08-28 기준)                  갈아 끼웁니다
    """
    줄 = (줄 or "").strip()
    if not 줄:
        return False
    return (bool(_기계줄.match(줄)) or bool(_숫자만.match(줄))
            or bool(_기준줄.search(줄)))


def 규모합치기(기존: str, 새줄: str) -> str:
    """기존 값에 새 줄을 얹습니다. 사람 글은 남깁니다.

    규모 · 피해 대상 · 한국 관련 유출 이 셋에 같이 씁니다.

        빈칸이면            그냥 씁니다
        기계 줄이 있으면    그 줄만 갈아 끼웁니다
        사람 글이 있으면    남기고 맨 앞에 붙입니다

    같은 줄이 이미 있으면 아무것도 안 합니다.
    """
    새줄 = (새줄 or "").strip()
    기존 = (기존 or "").strip()
    if not 새줄:
        return 기존
    if not 기존:
        return 새줄

    줄들 = [l.rstrip() for l in 기존.splitlines()]
    if any(l.strip() == 새줄 for l in 줄들):
        return 기존                       # 이미 같은 줄이 있습니다

    바꿈 = False
    나온것 = []
    for l in 줄들:
        if not 바꿈 and 기계가_쓴_줄(l):
            나온것.append(새줄)           # 옛 기계 줄을 갈아 끼웁니다
            바꿈 = True
        else:
            나온것.append(l)
    if not 바꿈:
        나온것.insert(0, 새줄)            # 사람 글 위에 붙입니다
    return "\n".join(나온것).strip()


@dataclass
class Place:
    """명부 한 줄. 세 갈래가 같은 모양을 씁니다."""

    갈래: str                       # forum · telegram · ransom
    이름: str
    주소: str = ""
    어니언: str = ""

    # ── 기계가 봅니다
    상태: str = "미확인"            # online · offline · 미확인 · 압수됨 · 인계됨
    확인일: str = field(default_factory=지금)
    회원수: int | None = None
    게시물수: int | None = None
    구독자수: int | None = None
    피해기업수: int | None = None
    어림수: bool = False            # t.me 가 8.12K 처럼 줄여 준 값인가
    주소이상: bool = False          # 명부의 주소가 이 갈래 것이 아닙니다
    두드림: bool = False            # 이 줄을 실제로 두드려 응답을 받았는가
    최근활동: str = ""

    # ── 갈래별 (노션 기존 칸)
    형식: str = ""                  # 랜섬. RaaS · IAB · DLS · 카딩 …
    종류: str = ""                  # 랜섬. group · market

    # ── 조사하면서 알게 되는 것. 전부 기존 칸에 들어갑니다.
    # 사람이 이미 쓴 칸은 안 건드립니다(빈칸만칸).
    언어: str = ""                  # 사용 언어. 본문 문자로 봅니다
    들어가는법: str = ""            # 가입이 필요한가, 무엇에 막히는가
    이전주소: str = ""              # 리다이렉트 전 주소 · 다른 미러
    이전이름: str = ""              # altname 같은 딴 이름
    어떤곳: str = ""                # 한 줄 설명
    가입필요: bool | None = None    # 모르면 None. False 와 다릅니다
    피해대상: str = ""              # 랜섬. 어느 업종이 당했나
    한국유출: str = ""              # 한국 피해 건수만. 이름은 안 적습니다
    연락수단: str = ""              # 랜섬. 그룹이 걸어 둔 연락 창구
    연결된곳: str = ""              # 이 곳이 가리키는 다른 명부의 곳들

    # ── 어떻게 알았나
    출처: list[str] = field(default_factory=list)
    못본이유: str = ""              # 못 봤으면 왜인지. 빈칸으로 두지 않습니다
    받은곳: str = ""
    살펴볼것: str = ""              # 사람이 손봐야 하는 것. 화면에 올립니다

    def 봤나(self) -> bool:
        return not self.못본이유

    def 규모줄(self) -> str:
        """기계가 쓸 한 줄. 꼴을 하나로 맞춥니다.

        지금 노션에는 사람마다 다른 꼴이 섞여 있어 RAG 가 읽기 어렵습니다.
        기계가 쓰는 줄만이라도 하나로 맞춥니다.
        """
        조각 = []
        if self.구독자수 is not None:
            조각.append(f"구독자 {self.구독자수:,}")
        if self.회원수 is not None:
            조각.append(f"회원 {self.회원수:,}")
        if self.게시물수 is not None:
            조각.append(f"게시물 {self.게시물수:,}")
        if self.피해기업수 is not None:
            조각.append(f"피해 기업 {self.피해기업수:,}")
        if not 조각:
            return ""
        꼬리 = " 안팎" if self.어림수 else ""
        return " · ".join(조각) + 꼬리 + f" ({self.확인일[:10]} 기준)"

    def 노션값(self, 기존: dict | str = "") -> dict:
        """노션에 넣을 값. **기존 칸만** 씁니다.

        기존 은 노션에 지금 있는 값입니다. {칸: 값} 으로 주면 합치는 칸에서
        사람 글을 남기고 섞습니다. 글자로 주면 규모로 봅니다.
        못 봤으면 상태와 확인일도 안 건드립니다. 틀린 값을 남기느니
        옛 값을 두는 편이 낫습니다.
        """
        # **두드리지 않았으면 아무것도 안 씁니다.**
        #
        # "미확인" 에는 두 가지가 섞여 있습니다.
        #
        #   두드렸는데 못 봤다   미리보기가 꺼진 채널. 미확인이 맞습니다.
        #                      online 이라고 적힌 것이 근거 없는 값입니다.
        #   두드리지도 못했다    API 응답에서 그 줄을 못 읽은 경우.
        #                      사람이 확인해 둔 값을 지우면 안 됩니다.
        #
        # 랜섬웨어 DB 508줄(online 126 · offline 379 · 압수됨 2 · 인계됨 1)이
        # 두 번째 경우로 날아갈 뻔했습니다. API 는 살아있는지를
        # locations[].available 에 담는데 최상위만 보고 있었습니다.
        if self.상태 == "미확인" and not self.두드림:
            return {}

        if isinstance(기존, str):
            기존 = {"규모": 기존}

        out: dict[str, object] = {"확인일": self.확인일[:10], "상태": self.상태}

        # 명부의 주소가 이 갈래 것이 아니면 조사를 못 했습니다. 그래도
        # 상태는 미확인으로 남깁니다. online 이라고 적혀 있는 것이 근거
        # 없는 값이기 때문입니다. 주소와 규모는 안 건드립니다.
        if self.주소이상:
            return out

        # 못 봤으면 상태와 확인일까지만 남깁니다. 언제 봤는데 못 봤는지가
        # 그 자체로 정보입니다. 규모는 안 건드립니다.
        if not self.봤나():
            return out

        새줄 = self.규모줄()
        if 새줄:
            out["규모"] = 규모합치기(기존.get("규모", ""), 새줄)

        if self.주소:
            out["주소"] = self.주소
        if self.어니언 and self.갈래 == "forum":
            out["어니언 주소"] = self.어니언
        if self.갈래 == "ransom":
            if self.형식:
                out["형식"] = self.형식
            if self.종류:
                out["종류"] = self.종류
            if self.최근활동:
                out["최근 활동"] = self.최근활동[:10]

        # 사람이 이미 쓴 칸은 명부 쪽에서 거릅니다(빈칸만칸). 여기서는
        # 알아낸 것을 그대로 담습니다.
        # 갈래마다 있는 칸이 다릅니다. 「연락수단」과 「피해 대상」은
        # 랜섬웨어 DB 에만 있습니다. 없는 칸을 보내면 명부 쪽에서
        # 걸러 내기는 하지만, 그때마다 「스키마에 없는 칸」 이라고
        # 알려서 줄마다 같은 말이 쌓입니다.
        쓸것 = [("사용 언어", self.언어),
               ("들어가는 법", self.들어가는법),
               ("이전 주소", self.이전주소),
               ("이전 이름·별칭", self.이전이름),
               ("어떤 곳인지", self.어떤곳),
               ("연결된 곳", self.연결된곳)]
        if self.갈래 == "ransom":
            쓸것 += [("연락수단", self.연락수단)]
        for 칸, 값 in 쓸것:
            if 값:
                out[칸] = 값

        # 두드려서 본 줄에만 「확인만 함」 을 넣습니다.
        #
        # 「시작 전」 은 값이 있는 것으로 봅니다. 빈칸만칸 이라 이미 뭔가
        # 적힌 줄은 안 건드립니다. 안 그러면 두 DB 의 「다음에 할 곳」
        # 뷰(조사 단계 = 시작 전 으로 거르는 작업 큐)가 한 판에 비어
        # 버립니다. 기계가 첫 화면을 본 것과 사람이 조사한 것은 다릅니다.
        out["조사 단계"] = "확인만 함"
        if self.가입필요 is not None:
            out["가입 필요"] = self.가입필요
        if self.출처:
            out["출처"] = list(self.출처)

        # 합치는 칸입니다. 기계 줄만 갈아 끼우고 사람 글은 남깁니다.
        # 꼬리를 붙여 둡니다. 이것이 있어야 다음 회차에 이 줄을 알아보고
        # 갈아 끼웁니다. 없으면 볼 때마다 한 줄씩 쌓입니다.
        꼬리 = f" ({self.확인일[:10]} 기준)"
        합칠것 = [("한국 관련 유출", self.한국유출)]
        if self.갈래 == "ransom":
            합칠것.insert(0, ("피해 대상", self.피해대상))
        for 칸, 값 in 합칠것:
            if 값:
                if not _기준줄.search(값):
                    값 = 값.rstrip() + 꼬리
                out[칸] = 규모합치기(기존.get(칸, ""), 값)
        return out

    def 숫자들(self) -> dict:
        """우리 쪽 SQLite 에 시계열로 쌓을 값."""
        return {k: v for k, v in {
            "회원수": self.회원수, "게시물수": self.게시물수,
            "구독자수": self.구독자수, "피해기업수": self.피해기업수,
        }.items() if v is not None}

    def dict(self) -> dict:
        return asdict(self)
