"""받아 온 쪽에서 값을 읽는 잔손질. 조사기 셋이 같이 씁니다.

여기 있는 것은 전부 **본 것만 말합니다.** 라틴 문자만 있는 쪽을 영어라고
적지 않습니다. 영어일 수도, 터키어일 수도, 독일어일 수도 있는데 문자만
보고는 못 가릅니다. 그럴 때는 빈칸으로 둡니다.

표준 라이브러리만 씁니다.
"""

from __future__ import annotations

import re

__all__ = ["언어판별", "html_lang", "글자만"]

# <html lang="ru"> 같은 표시가 있으면 그것을 씁니다. 우리가 세는 것보다
# 그 쪽이 스스로 밝힌 것이 낫습니다.
_LANG = re.compile(r'<html[^>]*\blang\s*=\s*["\']([A-Za-z\-]{2,8})', re.I)

_이름 = {
    "ko": "한국어", "en": "영어", "ru": "러시아어", "zh": "중국어",
    "ja": "일본어", "tr": "터키어", "de": "독일어", "fr": "프랑스어",
    "es": "스페인어", "pt": "포르투갈어", "vi": "베트남어", "id": "인도네시아어",
    "th": "태국어", "ar": "아랍어", "fa": "페르시아어", "uk": "우크라이나어",
    "hi": "힌디어", "it": "이탈리아어", "pl": "폴란드어", "nl": "네덜란드어",
}

# 문자만 보고 가릴 수 있는 것들입니다. 라틴 문자는 여기 없습니다.
_글자대 = [
    ("한국어", (0xAC00, 0xD7A3)), ("한국어", (0x1100, 0x11FF)),
    ("러시아어 계열(키릴 문자)", (0x0400, 0x04FF)),
    ("일본어", (0x3040, 0x30FF)),
    ("중국어 계열(한자)", (0x4E00, 0x9FFF)),
    ("아랍어 계열", (0x0600, 0x06FF)),
    ("태국어", (0x0E00, 0x0E7F)),
]


def html_lang(본문: str) -> str:
    """쪽이 스스로 밝힌 언어. 없으면 빈 글자."""
    m = _LANG.search(본문 or "")
    if not m:
        return ""
    코드 = m.group(1).lower().split("-")[0]
    return _이름.get(코드, "")


def 글자만(본문: str) -> str:
    """태그와 스크립트를 걷어냅니다. 언어를 세기 전에 씁니다."""
    본문 = re.sub(r"(?is)<(script|style)\b.*?</\1>", " ", 본문 or "")
    return re.sub(r"<[^>]+>", " ", 본문)


def 언어판별(본문: str, *, 최소: int = 12) -> str:
    """무슨 언어로 쓰나. **모르면 빈 글자를 돌려줍니다.**

    쪽이 밝힌 lang 을 먼저 보고, 없으면 본문 문자를 셉니다. 라틴 문자만
    있으면 빈칸입니다. 영어인지 터키어인지 문자만 보고는 못 가립니다.

    최소 는 이만큼은 나와야 센 것으로 치는 글자 수입니다. 메뉴에 섞인
    러시아어 몇 글자로 러시아어 채널이라고 적지 않으려는 것입니다.
    """
    말한것 = html_lang(본문)
    if 말한것:
        return 말한것

    글 = 글자만(본문)
    셈: dict[str, int] = {}
    for ch in 글:
        o = ord(ch)
        for 이름, (a, b) in _글자대:
            if a <= o <= b:
                셈[이름] = 셈.get(이름, 0) + 1
                break
    if not 셈:
        return ""
    이름, 수 = max(셈.items(), key=lambda kv: kv[1])
    return 이름 if 수 >= 최소 else ""
