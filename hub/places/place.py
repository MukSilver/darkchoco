def 덧붙임(p, 말: str) -> None:
    """살펴볼것 에 한 줄을 더합니다. **덮지 않습니다.**

    한 곳에서 볼 것이 둘일 수 있습니다. 압수 안내를 봤는데 어니언 후보도
    못 열었으면 둘 다 알려야 합니다. = 로 덮으면 나중 것이 앞 것을
    지웁니다. 실제로 어니언 문구가 압수 문구를 지우고 있었습니다.
    """
    말 = (말 or "").strip()
    if not 말 or 말 in (p.살펴볼것 or ""):
        return
    p.살펴볼것 = f"{p.살펴볼것} · {말}" if p.살펴볼것 else 말


