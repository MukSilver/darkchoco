"""한 줄에 조사기가 여럿 붙을 때 누가 이기는지.

랜섬 한 줄은 이미 조사기 둘이 봅니다.

    probe/ransom.py    ransomware.live /groups   상태 · 형식 · 이전 이름
    probe/forum.py     주소를 실제로 엶          언어 · 규모 · 연결된 곳

여기에 dls-observatory 가 붙으면 셋이 됩니다. 예전에는 이 합치는 규칙이
`run.py` 의 `_열기()` 안에 손으로 박혀 있었습니다. 칸 이름을 문자열로
나열하고 있어서, 조사기가 하나 늘 때마다 그 함수가 길어졌습니다.

**조사기를 더할 때 인자를 하나 더 주면 되게 합니다. if 를 더하지
않습니다.**

규칙은 넷입니다.

    이긴것    상태 — 실제로 두드린 쪽이 이깁니다
    빈칸만    나머지 거의 전부 — 먼저 채워진 것을 안 덮습니다
    이어붙임  받은곳 · 출처 · 살펴볼것 — 어디서 왔는지를 다 남깁니다
    합집합    유통자리 · 처음본곳 — 목록이라 겹치는 것만 지웁니다

「빈칸만」이 기본인 이유는 조사기마다 **아는 것이 다르기** 때문입니다.
API 는 형식과 이전 이름을 알고, 페이지는 언어와 규모를 압니다. 둘이
같은 칸을 다르게 채우는 일은 드물고, 그럴 때는 **먼저 온 쪽이 더 가까이
본 쪽**입니다(주소를 실제로 연 쪽을 바탕으로 삼습니다).
"""

from __future__ import annotations

from dataclasses import fields as _칸들

from hub.places.place import Place

__all__ = ["합치기", "이어붙임칸", "합집합칸", "안건드림칸"]


# 이어 붙입니다. 어디서 왔는지를 지우면 나중에 왜 그 값인지 못 찾습니다.
이어붙임칸 = ("받은곳",)

# 목록입니다. 겹치는 것만 지우고 순서는 지킵니다.
합집합칸 = ("출처", "유통자리", "처음본곳")

# 바탕 것을 그대로 둡니다. 얹는 쪽 값을 안 봅니다.
#
#   갈래·이름·주소     그 줄이 무엇인가입니다. 바뀌면 다른 줄입니다
#   확인일             언제 봤나. 바탕 것이 이번 판입니다
#   못본이유           바탕이 못 봤으면 못 본 것입니다
#   두드림·상태        아래에서 따로 봅니다
안건드림칸 = ("갈래", "이름", "확인일", "못본이유", "두드림", "상태",
           "주소이상", "살펴볼것")


def _빈값(v) -> bool:
    """빈칸인가. False 와 0 은 빈칸이 아닙니다."""
    if v is None:
        return True
    if isinstance(v, str):
        return not v.strip()
    if isinstance(v, (list, tuple, set, dict)):
        return not v
    return False


def 합치기(바탕: Place, *얹을것: Place) -> Place:
    """바탕에 얹을것들을 겹쳐 한 줄로 만듭니다.

    바탕을 **그 자리에서 고칩니다.** 돌려주는 것도 바탕입니다.
    바탕은 보통 주소를 실제로 연 결과입니다. 가장 가까이 본 것입니다.

    >>> 합치기(연것, API가준것)            # 지금
    >>> 합치기(연것, API가준것, DLS가준것)  # 나중. if 를 안 더합니다
    """
    이름들 = [f.name for f in _칸들(Place)]

    for 위 in 얹을것:
        if 위 is None:
            continue

        # ── 상태: 얹는 쪽이 실제로 두드렸으면 그것이 이깁니다
        #
        # 「바탕이 더 가까이 봤으니 바탕이 이긴다」가 아닙니다. 랜섬에서
        # 얹는 쪽은 ransomware.live /groups 인데, 그 API 의 본업이
        # 「이 그룹이 살아있나」입니다. 우리 쪽 연결 실패보다 믿을 만하고,
        # 미러 하나가 떠 있어도 그룹은 접혔을 수 있습니다.
        #
        # 그래서 **더 믿을 만한 것을 뒤에 놓습니다.** 부르는 쪽이 순서로
        # 정합니다. 여기서 갈래를 보고 가르지 않습니다.
        if 위.두드림:
            바탕.상태 = 위.상태
            바탕.두드림 = True

        for 칸 in 이름들:
            if 칸 in 안건드림칸:
                continue
            새값 = getattr(위, 칸, None)
            if _빈값(새값):
                continue

            if 칸 in 이어붙임칸:
                옛값 = getattr(바탕, 칸, "") or ""
                if 새값 not in 옛값:
                    바탕.받은곳 = f"{새값} + {옛값}" if 옛값 else str(새값)
                continue

            if 칸 in 합집합칸:
                옛값 = list(getattr(바탕, 칸, None) or [])
                for x in 새값:
                    if x not in 옛값:
                        옛값.append(x)
                setattr(바탕, 칸, 옛값)
                continue

            # ── 나머지는 빈칸만 채웁니다
            if _빈값(getattr(바탕, 칸, None)):
                setattr(바탕, 칸, 새값)

        # 살펴볼 것은 지우면 안 됩니다. 사람이 봐야 하는 줄입니다.
        if 위.살펴볼것:
            from hub.places.place import 덧붙임
            for 조각 in 위.살펴볼것.split(" · "):
                덧붙임(바탕, 조각)

    return 바탕
